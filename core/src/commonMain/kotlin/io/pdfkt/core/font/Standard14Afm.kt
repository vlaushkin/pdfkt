// Adobe Font Metrics File Format Specification, technical note #5004
// (7 October 1998) §4 "AFM File Structure", §7.1 "Global Font
// Information", §8 "Individual Character Metrics";
// ISO 32000-2:2020 §9.6.2.2 "Standard Type 1 fonts (standard 14 fonts)"

/**
 * The metrics of one of the fourteen fonts of §9.6.2.2, as the lines of an
 * AFM file — the form [AfmFont.parse] reads and the form Adobe published
 * them in.
 *
 * A PDF file that names one of these fonts carries no widths and no font
 * descriptor: §9.6.2.2 lets `FirstChar`, `LastChar`, `Widths` and
 * `FontDescriptor` be absent together and puts the obligation on the
 * reader — "For compatibility reasons PDF processors shall provide glyph
 * widths and font descriptor data for those standard fonts for use in
 * processing PDF files when the entries are absent." A writer is in the
 * same position for the opposite reason: it has to know the widths in
 * order to decide where a line breaks, and nothing in the file will tell
 * it. This is where it knows them from.
 *
 * Line-oriented because AFM is: "The file format is line-oriented, each
 * line beginning with a property (key) name, followed by the values for
 * that property" (#5004 §3). Kept as a list of lines rather than one
 * string so that no constant here approaches a limit of any target, and
 * built per font on demand — a document that sets Helvetica never
 * materialises the other thirteen.
 */
internal fun standard14AfmLines(name: Standard14Name): List<String> = when (name) {
    Standard14Name.TIMES_ROMAN -> timesRomanAfm()
    Standard14Name.HELVETICA -> helveticaAfm()
    Standard14Name.COURIER -> courierAfm()
    Standard14Name.SYMBOL -> symbolAfm()
    Standard14Name.TIMES_BOLD -> timesBoldAfm()
    Standard14Name.HELVETICA_BOLD -> helveticaBoldAfm()
    Standard14Name.COURIER_BOLD -> courierBoldAfm()
    Standard14Name.ZAPF_DINGBATS -> zapfDingbatsAfm()
    Standard14Name.TIMES_ITALIC -> timesItalicAfm()
    Standard14Name.HELVETICA_OBLIQUE -> helveticaObliqueAfm()
    Standard14Name.COURIER_OBLIQUE -> courierObliqueAfm()
    Standard14Name.TIMES_BOLD_ITALIC -> timesBoldItalicAfm()
    Standard14Name.HELVETICA_BOLD_OBLIQUE -> helveticaBoldObliqueAfm()
    Standard14Name.COURIER_BOLD_OBLIQUE -> courierBoldObliqueAfm()
}

